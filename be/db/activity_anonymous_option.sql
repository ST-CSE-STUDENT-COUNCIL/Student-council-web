-- 목적: 활동(설문조사, 수요조사) 생성 시 익명/기명 모드를 선택할 수 있도록 함
--   - is_anonymous = true  (기본값): 익명 모드 - 응답자 개인정보 저장하지 않음
--   - is_anonymous = false : 기명 모드 - 응답자 이름/학번 등 개인정보 저장
-- ============================================================================

-- 1. activities 테이블에 is_anonymous 컬럼 추가
ALTER TABLE activities
ADD COLUMN IF NOT EXISTS is_anonymous BOOLEAN DEFAULT true;

COMMENT ON COLUMN activities.is_anonymous IS '익명 여부 (true: 익명 모드 - 응답자 정보 비공개, false: 기명 모드 - 응답자 정보 수집). 설문조사/수요조사에서 주로 사용';
